def test_spec_router_roundtrip_canonical():
    """Verify spec_router renders and imports canonical template without data loss."""
    canonical_path = os.path.join(
        os.path.dirname(__file__), "..", "templates", "pipeline_onboarding_template.json"
    )
    with open(canonical_path, "r", encoding="utf-8") as f:
        original = json.load(f)

    # 1. Render to JSON
    res = client.post("/api/spec/render", json={"spec": original, "format": "json"})
    assert res.status_code == 200
    rendered_json = res.json()["content"]
    assert "dfg_template_example" in rendered_json
    assert "df_template_ingest" in rendered_json

    # 2. Render to YAML
    res = client.post("/api/spec/render", json={"spec": original, "format": "yaml"})
    assert res.status_code == 200
    rendered_yaml = res.json()["content"]
    assert "dfg_template_example" in rendered_yaml

    # 3. Import back
    res = client.post("/api/spec/import", json={"content": rendered_json, "format": "json"})
    assert res.status_code == 200
    imported = res.json()["spec"]
    assert "root" in imported or "dataflow_group_id" in imported


