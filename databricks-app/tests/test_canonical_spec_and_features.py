def test_v140_removed_attributes_are_absent_from_the_shipped_frontend(frontend_text):
    """The builder must not offer a field the framework rejects.

    This asserts on the BUILT bundle, not the source registry, because that is the gap this test
    closes: `web/dist/` is committed Vite output and is only regenerated by `npm run build`. Edit
    registry.js, forget the rebuild, and the app keeps serving the old form -- authors keep filling
    in `generate_surrogate_key`, and every spec they produce now fails onboarding validation with
    an error about an attribute the UI told them to set.
    """
    html = frontend_text
    for removed in (
        "generate_surrogate_key",
        "surrogate_key_columns",
        "surrogate_key_exclude_columns",
        "recon_mode",
        "normalize_column_names",
        "FULL_SNAPSHOT_CDC_NO_PK",
    ):
        assert removed not in html, (
            f"{removed} is still in the shipped frontend bundle -- run `npm run build` in "
            "databricks-app/web after changing registry.js or Builder.jsx"
        )


